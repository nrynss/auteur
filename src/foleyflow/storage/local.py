"""Filesystem backend — the offline/dev default.

Layout under `root` mirrors the B2 key space exactly, so switching backends
never changes a key. With root="sfx_cache" and the cache prefix disabled this
is byte-for-byte the media core's existing cache directory, which is why the
161 WAVs generated by the prior pipeline can be dropped straight in.
"""

import hashlib
import os
import shutil
import tempfile
from typing import Optional

from foleyflow.storage.base import (
    ObjectHead,
    ObjectNotFound,
    PreconditionFailed,
    StorageError,
    validate_key,
)


_HASH_CHUNK = 1 << 20


def _sha256_file(path: str) -> str:
    """Full-content hash, chunked so a large source video does not land in
    memory. LocalBackend's own hashlib loop rather than a shared helper: the
    storage module stays free of the media pipeline modules (see the module
    docstring), and this is three lines of stdlib either way."""
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(_HASH_CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


class LocalBackend:
    def __init__(self, root: str):
        self.root = os.path.abspath(root)

    def _path(self, key: str) -> str:
        """Resolve a storage key to a path under root.

        Validation is shared with every other backend via `validate_key` rather
        than relying on this one's native path handling — see base.validate_key
        for why that matters.
        """
        return os.path.join(self.root, *validate_key(key))

    def exists(self, key: str) -> bool:
        return os.path.exists(self._path(key))

    def head(self, key: str) -> ObjectHead:
        """Size and sha256 of a stored object.

        Hashing the file is free on a local backend, so it is included rather
        than left for a caller to download the bytes a second time. B2 cannot
        do this (see B2Backend.head); the dossier's sha256 column is therefore
        fuller on a local backend, which is honest rather than misleading —
        the value really is the hash of the stored object.
        """
        path = self._path(key)
        try:
            size = os.path.getsize(path)
        except FileNotFoundError as e:
            raise ObjectNotFound(f"no object at {key!r}") from e
        except OSError as e:
            raise StorageError(f"could not stat {key!r}: {e.strerror}") from e
        return ObjectHead(size_bytes=size, sha256=_sha256_file(path))

    def get(self, key: str, dest_path: str) -> str:
        src = self._path(key)
        if not os.path.exists(src):
            # Names the key, not the resolved path: this message reaches API
            # clients and permanent run records.
            raise ObjectNotFound(f"no object at {key!r}")
        os.makedirs(os.path.dirname(os.path.abspath(dest_path)), exist_ok=True)
        if os.path.abspath(src) != os.path.abspath(dest_path):
            shutil.copyfile(src, dest_path)
        return dest_path

    def get_bytes(self, key: str) -> bytes:
        src = self._path(key)
        try:
            with open(src, "rb") as f:
                return f.read()
        except FileNotFoundError as e:
            raise ObjectNotFound(f"no object at {key!r}") from e
        except OSError as e:
            raise StorageError(f"could not read {key!r}: {e.strerror}") from e

    def put(self, key: str, src_path: str, content_type: Optional[str] = None) -> str:
        with open(src_path, "rb") as f:
            return self.put_bytes(key, f.read(), content_type)

    def put_bytes(self, key: str, data: bytes,
                  content_type: Optional[str] = None) -> str:
        dest = self._path(key)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        # Written to a unique temp file in the destination directory and then
        # renamed, so a crash mid-write cannot leave a truncated object that a
        # later `exists()` reports as present.
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(dest), suffix=".part")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp, dest)
        except OSError as e:
            raise StorageError(f"could not write {key!r}: {e.strerror}") from e
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
        return key

    def put_if_absent(self, key: str, data: bytes,
                      content_type: Optional[str] = None) -> str:
        """Atomic create — the object appears complete or not at all.

        Written to a temp file first and then hard-linked into place.
        `os.link` is the filesystem's test-and-set (it raises FileExistsError
        rather than clobbering), so two threads racing here still cannot both
        succeed — and unlike `O_CREAT | O_EXCL` followed by a write, there is no
        window in which the object exists but is empty.

        That window was reachable: a run record is written with this method and
        read back by `GET /runs/{id}` while a `--wait` client polls, so a reader
        landing between the create and the write got a zero-byte file and a
        JSONDecodeError for a run that was in fact fine.
        """
        dest = self._path(key)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(dest), suffix=".part")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.link(tmp, dest)
        except FileExistsError as e:
            raise PreconditionFailed(f"object already exists at {key!r}") from e
        except OSError as e:
            raise StorageError(f"could not create {key!r}: {e.strerror}") from e
        finally:
            if os.path.exists(tmp):
                os.unlink(tmp)
        return key

    def signed_url(self, key: str, expires_s: int = 3600) -> str:
        path = self._path(key)
        if not os.path.exists(path):
            raise ObjectNotFound(f"no object at {key!r}")
        return "file:///" + path.replace(os.sep, "/").lstrip("/")

    def list_keys(self, prefix: str):
        """Walk the directory tree under `prefix` and return storage keys.

        Emits keys, not filesystem paths, so callers cannot tell which backend
        they are on. Sorted for the same reason as B2's listing: ULID-named
        objects then arrive in creation order.
        """
        base = os.path.join(self.root, *[p for p in prefix.split("/") if p])
        if not os.path.isdir(base):
            return []
        keys = []
        for dirpath, _dirnames, filenames in os.walk(base):
            for filename in filenames:
                if filename.endswith(".part"):
                    continue        # an in-progress write is not an object
                full = os.path.join(dirpath, filename)
                rel = os.path.relpath(full, self.root).replace(os.sep, "/")
                keys.append(rel)
        return sorted(keys)

    def __repr__(self) -> str:
        return f"LocalBackend(root={self.root!r})"
