"""Offline tests for the storage-backed sfx_fn seam.

generate_canonical_wav is monkeypatched everywhere — a real call would be a
paid fal request. Any test that reaches it without patching is a bug in the
test, so the fake records its calls and assertions check the count.
"""

import os

import pytest

from foleyflow import sfx as core_sfx
from foleyflow.routing import SfxRequest
from foleyflow import sfx_cache
from foleyflow.storage import LocalBackend


def _req(prompt="rain on cobblestone", duration=8.0,
         endpoint="cassetteai/sound-effects-generator") -> SfxRequest:
    return SfxRequest(endpoint=endpoint, prompt=prompt,
                      duration_s=duration, category="ambience")


def _write_real_wav(path, seconds=0.25):
    """Actual audio, for the prewarm tests.

    Unlike `fake_generate`, prewarm canonicalizes what the provider handed back
    — real ffmpeg on a real file — so a placeholder byte string would fail at
    the conversion rather than at the assertion under test.
    """
    import numpy as np
    import soundfile as sf

    n = int(48000 * seconds)
    tone = 0.1 * np.sin(2 * np.pi * 220 * np.arange(n) / 48000)
    sf.write(path, np.column_stack([tone, tone]).astype(np.float32), 48000,
             format="WAV", subtype="FLOAT")
    return path


@pytest.fixture
def fake_generate(monkeypatch):
    """Replace the billed generation path with a local WAV writer."""
    calls = []

    def _fake(request, dest_path):
        calls.append((request.endpoint, request.prompt, request.duration_s))
        os.makedirs(os.path.dirname(os.path.abspath(dest_path)), exist_ok=True)
        with open(dest_path, "wb") as f:
            f.write(b"generated-" + str(len(calls)).encode())
        return dest_path

    monkeypatch.setattr(sfx_cache, "generate_canonical_wav", _fake)
    return calls


# -- cache key compatibility --

def test_empty_variant_key_is_identical_to_the_media_core(monkeypatch):
    """The 161 clips generated by the prior pipeline must keep resolving after
    they are uploaded to B2. If this fails, the whole cache is orphaned."""
    for endpoint, prompt, duration in [
        ("cassetteai/sound-effects-generator", "rain on cobblestone", 8.0),
        ("fal-ai/elevenlabs/sound-effects/v2", "heavy armored boots", 1.75),
        ("fal-ai/mmaudio-v2/text-to-audio", "match strike", 2.5),
    ]:
        assert (sfx_cache.cache_key(endpoint, prompt, duration)
                == core_sfx.cache_key(endpoint, prompt, duration))


def test_variant_changes_the_key(monkeypatch):
    base = sfx_cache.cache_key("ep", "prompt", 3.0)
    assert sfx_cache.cache_key("ep", "prompt", 3.0, "r2") != base
    assert sfx_cache.cache_key("ep", "prompt", 3.0, "r2") != sfx_cache.cache_key("ep", "prompt", 3.0, "r3")


def test_variant_is_stable_across_calls():
    a = sfx_cache.cache_key("ep", "prompt", 3.0, "r2")
    b = sfx_cache.cache_key("ep", "prompt", 3.0, "r2")
    assert a == b


# -- acquisition --

def test_cache_miss_generates_once_and_uploads(tmp_path, fake_generate):
    backend = LocalBackend(str(tmp_path / "store"))
    fn = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "work"))

    path = fn(_req())
    assert os.path.exists(path)
    assert len(fake_generate) == 1
    assert backend.exists(sfx_cache.cache_object_key(
        "cassetteai/sound-effects-generator", "rain on cobblestone", 8.0))


def test_second_request_hits_storage_without_regenerating(tmp_path, fake_generate):
    backend = LocalBackend(str(tmp_path / "store"))

    fn_a = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "work_a"))
    fn_a(_req())
    assert len(fake_generate) == 1

    # A fresh render, fresh work dir — the shared backend must serve it.
    fn_b = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "work_b"))
    path = fn_b(_req())
    assert len(fake_generate) == 1, "cache hit must not re-bill"
    with open(path, "rb") as f:
        assert f.read() == b"generated-1"


def test_repeated_request_in_one_render_reuses_the_local_file(tmp_path, fake_generate):
    backend = LocalBackend(str(tmp_path / "store"))
    fn = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "work"))
    assert fn(_req()) == fn(_req())
    assert len(fake_generate) == 1


# -- the regenerate fix --

def test_variant_forces_a_real_regeneration(tmp_path, fake_generate):
    """SPEC.md §5 targeted repair. Without the variant nonce this returns the
    byte-identical stem from cache while the UI reports a new take."""
    backend = LocalBackend(str(tmp_path / "store"))
    work = str(tmp_path / "work")

    v1 = sfx_cache.backed_sfx_fn(backend, work)(_req())
    with open(v1, "rb") as f:
        v1_bytes = f.read()

    v2 = sfx_cache.backed_sfx_fn(backend, work, variant_fn=lambda _r: "r2")(_req())
    with open(v2, "rb") as f:
        v2_bytes = f.read()

    assert len(fake_generate) == 2, "regeneration must actually be billed"
    assert v1 != v2, "each take needs its own address for version lineage"
    assert v1_bytes != v2_bytes, "the regenerated stem must be different audio"


def test_regenerated_variant_is_itself_cached(tmp_path, fake_generate):
    """v2 is content-addressed too, so re-rendering the repaired mix is free."""
    backend = LocalBackend(str(tmp_path / "store"))
    variant = lambda _r: "r2"

    sfx_cache.backed_sfx_fn(backend, str(tmp_path / "w1"), variant_fn=variant)(_req())
    sfx_cache.backed_sfx_fn(backend, str(tmp_path / "w2"), variant_fn=variant)(_req())
    assert len(fake_generate) == 1


def test_variant_applies_per_request_not_globally(tmp_path, fake_generate):
    """Regenerating one event must leave every other event on its cache hit —
    otherwise 'repair only what changed' re-bills the whole timeline."""
    backend = LocalBackend(str(tmp_path / "store"))
    work = str(tmp_path / "work")
    ambience = _req(prompt="rain on cobblestone")
    footsteps = _req(prompt="heavy armored boots", duration=1.75)

    warm = sfx_cache.backed_sfx_fn(backend, work)
    warm(ambience)
    warm(footsteps)
    assert len(fake_generate) == 2

    # Repair pass: only the footsteps request carries a variant.
    def only_footsteps(req):
        return "r2" if req.prompt == "heavy armored boots" else ""

    repair = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "repair"),
                                     variant_fn=only_footsteps)
    repair(ambience)
    repair(footsteps)
    assert len(fake_generate) == 3, "exactly one new generation"
    assert fake_generate[-1][1] == "heavy armored boots"


# -- observability --

def test_on_event_reports_cache_status(tmp_path, fake_generate):
    backend = LocalBackend(str(tmp_path / "store"))
    seen = []
    fn = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "w1"), on_event=seen.append)
    fn(_req())
    assert seen[-1]["cached"] is False

    fn2 = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "w2"), on_event=seen.append)
    fn2(_req())
    assert seen[-1]["cached"] is True


def test_observer_errors_never_break_a_render(tmp_path, fake_generate):
    backend = LocalBackend(str(tmp_path / "store"))

    def boom(_payload):
        raise RuntimeError("observer exploded")

    fn = sfx_cache.backed_sfx_fn(backend, str(tmp_path / "work"), on_event=boom)
    assert os.path.exists(fn(_req()))


# -- prewarm: the Genblaze fan-out in front of the cache ---------------------

def test_prewarm_stores_each_stem_at_its_existing_address(tmp_path, monkeypatch):
    """Warming the cache is a scheduling change, not an addressing one.

    If prewarm stored anywhere but the address `backed_sfx_fn` looks in, every
    render would warm the cache and then miss it — and the ~170 stems already
    in B2 would be unreachable.
    """
    from foleyflow import stems

    backend = LocalBackend(str(tmp_path / "store"))
    work = str(tmp_path / "work")
    raw = tmp_path / "raw.wav"
    _write_real_wav(str(raw))

    def _generate_many(requests, **kwargs):
        return [stems.StemResult(request=r, served=r, local_path=str(raw))
                for r in requests]

    monkeypatch.setattr(stems, "generate_many", _generate_many)

    request = _req()
    results = sfx_cache.prewarm(backend, work, [request])
    assert len(results) == 1

    expected = sfx_cache.cache_object_key(
        request.endpoint, request.prompt, request.duration_s)
    assert backend.exists(expected)

    # And the pull path finds it without generating anything.
    def _explode(*_a, **_k):
        raise AssertionError("prewarmed stem was not found in the cache")

    monkeypatch.setattr(sfx_cache, "generate_canonical_wav", _explode)
    assert os.path.exists(sfx_cache.backed_sfx_fn(backend, work)(request))


def test_prewarm_skips_requests_the_cache_already_holds(tmp_path, monkeypatch,
                                                        fake_generate):
    from foleyflow import stems

    backend = LocalBackend(str(tmp_path / "store"))
    work = str(tmp_path / "work")
    request = _req()
    sfx_cache.backed_sfx_fn(backend, work)(request)      # populate

    asked = []
    monkeypatch.setattr(stems, "generate_many",
                        lambda requests, **kw: asked.extend(requests) or [])

    assert sfx_cache.prewarm(backend, str(tmp_path / "fresh"), [request]) == []
    assert asked == []


def test_a_stem_prewarm_could_not_produce_is_left_for_the_pull_path(
        tmp_path, monkeypatch, fake_generate):
    """Failure semantics stay where they were: a render fails at the mix, not
    in a warm-up step."""
    from foleyflow import stems

    backend = LocalBackend(str(tmp_path / "store"))
    work = str(tmp_path / "work")
    request = _req()

    monkeypatch.setattr(stems, "generate_many", lambda requests, **kw: [
        stems.StemResult(request=r, error="provider down") for r in requests])

    results = sfx_cache.prewarm(backend, work, [request])
    assert [r.ok for r in results] == [False]
    # `fake_generate` still stands in for the billed call, so the pull path
    # succeeds — the point is that it was reached at all.
    assert os.path.exists(sfx_cache.backed_sfx_fn(backend, work)(request))
